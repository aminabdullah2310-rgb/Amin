package com.example.model

import androidx.room.Entity
import androidx.room.PrimaryKey

@Entity(tableName = "matches")
data class MatchRecord(
    @PrimaryKey val id: String,
    val weekNumber: Int,
    val homeClubId: String,
    val homeClubName: String,
    val awayClubId: String,
    val awayClubName: String,
    val homeScore: Int = 0,
    val awayScore: Int = 0,
    val isFinished: Boolean = false,
    val possessionHome: Int = 50,
    val shotsHome: Int = 0,
    val shotsAway: Int = 0,
    val offsidesHome: Int = 0,
    val offsidesAway: Int = 0,
    val foulsHome: Int = 0,
    val foulsAway: Int = 0,
    val homeFormation: String = "4-3-3",
    val awayFormation: String = "4-2-3-1",
    val homeTacticalStyle: String = "Balanced",
    val awayTacticalStyle: String = "Counter-Attack",
    val offsideTrapActive: Boolean = true,
    val smartOffsideAnalysis: String = "", // Generated by Gemini AI
    val tacticalScoreRating: Int = 85, // 0-100 rating from AI coach
    val matchEventsJson: String = "[]",
    val matchDateText: String = "Week 1 - League Match"
)
